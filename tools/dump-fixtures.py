#!/usr/bin/env python3
"""Run a model under onnxruntime and keep every intermediate tensor.

    dump-fixtures.py model.onnx outdir/ [phoneme-string]

Writes outdir/inputs.npz, outdir/values/<n>.npy for every node output, and
outdir/manifest.sexp naming them in graph order.

This is the harness the whole port hangs off.  A TTS engine that is 2755 nodes
deep gives one bit of feedback at the end — the audio sounds wrong — and that is
not enough to debug an arithmetic mistake in node 900.  With a golden value for
every node, a wrong answer names the node that first diverged, which turns the
whole thing from a research problem into a list.

The model is made DETERMINISTIC before dumping: VITS samples noise in two places
(the stochastic duration predictor, and the flow), so back-to-back runs of the
same input differ.  Both are scaled by values we pass in — noise_scale and
noise_w — so zeroing those makes the graph a pure function of its input without
touching the weights.  The check at the end proves it rather than assuming it:
two runs must agree bit for bit, or the fixtures are not fixtures.
"""
import json
import sys
from pathlib import Path

import numpy as np
import onnx
import onnxruntime as ort


def phoneme_ids(config, text_phonemes):
    """Piper's id sequence: BOS, then every phoneme followed by a pad, then EOS."""
    m = config["phoneme_id_map"]
    missing = [p for p in text_phonemes if p not in m]
    if missing:
        raise SystemExit(f"phonemes not in this voice's map: {missing!r}")
    ids = list(m["^"])
    for p in text_phonemes:
        ids.extend(m[p])
        ids.extend(m["_"])
    ids.extend(m["$"])
    return np.array([ids], dtype=np.int64)


def expose_all_values(model):
    """Every node output becomes a graph output, so one run yields all of them."""
    g = model.graph
    have = {o.name for o in g.output}
    names = []
    for n in g.node:
        for o in n.output:
            if o and o not in have:
                g.output.extend([onnx.ValueInfoProto(name=o)])
                have.add(o)
                names.append(o)
    return [o.name for o in g.output]


def main():
    if len(sys.argv) < 3:
        raise SystemExit(__doc__)
    src, outdir = Path(sys.argv[1]), Path(sys.argv[2])
    # "Hello world." in the voice's own IPA -- what chord's G2P produces for it.
    # Short on purpose: the fixtures are per-node dumps of a 2755-node graph, and
    # every extra phoneme costs across all of them.
    phonemes = list(sys.argv[3]) if len(sys.argv) > 3 else list("həlˈoʊ wˈɜːld.")
    (outdir / "values").mkdir(parents=True, exist_ok=True)

    config = json.loads(Path(str(src) + ".json").read_text())
    ids = phoneme_ids(config, phonemes)
    lengths = np.array([ids.shape[1]], dtype=np.int64)
    # [noise_scale, length_scale, noise_w].  The two noise terms are zeroed: see
    # the module docstring.  length_scale stays at the voice's own default so the
    # duration arithmetic is exercised rather than bypassed.
    scales = np.array([0.0, config["inference"]["length_scale"], 0.0], dtype=np.float32)
    feeds = {"input": ids, "input_lengths": lengths, "scales": scales}

    model = onnx.load(str(src))
    names = expose_all_values(model)
    so = ort.SessionOptions()
    so.graph_optimization_level = ort.GraphOptimizationLevel.ORT_DISABLE_ALL
    sess = ort.InferenceSession(model.SerializeToString(), so, providers=["CPUExecutionProvider"])

    outs = sess.run(names, feeds)
    again = sess.run(["output"], feeds)[0]
    ref = outs[names.index("output")]
    if not np.array_equal(ref, again):
        raise SystemExit("model is not deterministic even with the noise scales at 0 — "
                         "fixtures would be meaningless; find the other noise source first")

    manifest = []
    for i, (nm, val) in enumerate(zip(names, outs)):
        val = np.asarray(val)
        np.save(outdir / "values" / f"{i}.npy", val)
        manifest.append((i, nm, str(val.dtype), list(val.shape)))

    np.savez(outdir / "inputs.npz", **feeds)
    # ...and one .npy per input, so the Lisp gate feeds the model the same bytes
    # onnxruntime saw without needing a zip reader to find out what they were.
    (outdir / "inputs").mkdir(exist_ok=True)
    for k, v in feeds.items():
        np.save(outdir / "inputs" / f"{k}.npy", v)
    with open(outdir / "manifest.sexp", "w") as f:
        f.write(";;; Generated by tools/dump-fixtures.py — do not edit.\n")
        f.write(f"(:phonemes {json.dumps(''.join(phonemes))}\n")
        f.write(f" :audio-samples {int(np.prod(ref.shape))}\n")
        f.write(f" :sample-rate {config['audio']['sample_rate']}\n")
        f.write(" :values (\n")
        for i, nm, dt, shape in manifest:
            f.write(f'  ({i} "{nm}" "{dt}" ({" ".join(str(s) for s in shape)}))\n')
        f.write("))\n")

    total = sum((outdir / "values" / f"{i}.npy").stat().st_size for i, *_ in manifest)
    print(f"{len(manifest)} values, {total/1e6:.0f} MB")
    print(f"audio: {ref.shape} = {np.prod(ref.shape)/config['audio']['sample_rate']:.2f} s, "
          f"peak {np.abs(ref).max():.4f}")


if __name__ == "__main__":
    main()
